import type { Metadata } from "next";
import { getServerDictionary } from "@/lib/i18n/server";
import { getOperator } from "@/lib/legal";
import { REPO_URL, SITE_URL } from "@/lib/site";
import { LastUpdated, legalLang } from "../updated";

export async function generateMetadata(): Promise<Metadata> {
  const { dict } = await getServerDictionary();
  return { title: dict.legal.imprint, alternates: { canonical: "/legal/imprint" } };
}

export default async function ImprintPage() {
  const { locale } = await getServerDictionary();
  const lang = legalLang(locale);
  const op = getOperator();
  const domain = new URL(SITE_URL).host;

  const contact = (
    <p>
      {op.name}
      <br />
      {op.address}
      <br />
      <a href={`mailto:${op.email}`}>{op.email}</a>
    </p>
  );

  if (lang === "de") {
    return (
      <>
        <h1>Impressum</h1>
        <h2>Betreiber von {domain}</h2>
        {contact}
        <p>
          Verantwortlich für den Inhalt dieser Website ist die oben genannte Person.
        </p>

        <h2>Haftungsausschluss</h2>
        <p>
          Die Inhalte dieser Website werden mit grösster Sorgfalt erstellt. Für die
          Richtigkeit, Vollständigkeit und Aktualität wird jedoch keine Gewähr
          übernommen. Bilder und Videos, die während eines Turniers entstehen, werden
          von KI-Modellen auf Basis der Prompts der Spielenden generiert; für diese
          Inhalte sind die jeweiligen Veranstaltenden und Spielenden verantwortlich.
        </p>

        <h2>Links zu anderen Websites</h2>
        <p>
          Für Inhalte externer Websites, auf die verlinkt wird, sind ausschliesslich
          deren Betreiber verantwortlich.
        </p>

        <h2>Urheberrecht und Open Source</h2>
        <p>
          Der Quellcode von Prompt Battle ist unter der GNU Affero General Public
          License v3.0 (AGPL-3.0) auf <a href={REPO_URL}>GitHub</a> veröffentlicht.
          Name, Logo und Domain „Prompt Battle“ / {domain} sind davon nicht erfasst.
        </p>
        <LastUpdated lang="de" />
      </>
    );
  }

  return (
    <>
      <h1>Imprint</h1>
      <h2>Operator of {domain}</h2>
      {contact}
      <p>The person named above is responsible for the content of this website.</p>

      <h2>Disclaimer</h2>
      <p>
        The content of this website is created with great care, but no guarantee is
        given for its accuracy, completeness or timeliness. Images and videos created
        during a tournament are generated by AI models from the players’ prompts; the
        respective hosts and players are responsible for that content.
      </p>

      <h2>External links</h2>
      <p>
        The operators of linked external websites are solely responsible for their
        content.
      </p>

      <h2>Copyright and open source</h2>
      <p>
        The source code of Prompt Battle is published under the GNU Affero General
        Public License v3.0 (AGPL-3.0) on <a href={REPO_URL}>GitHub</a>. The name,
        logo and domain “Prompt Battle” / {domain} are not covered by that license.
      </p>
      <LastUpdated lang="en" />
    </>
  );
}
